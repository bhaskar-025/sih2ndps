import { Request, Response } from 'express';
import { RoadmapService } from '../services/roadmap.service';
import { ProjectApprovalStatus } from '../models/ProjectApproval';

export class RoadmapController {
  /**
   * @route POST /api/v1/projects/:id/generate-roadmap
   * @desc Run rule engine and generate statutory roadmap
   */
  static async generateRoadmap(req: Request, res: Response): Promise<void> {
    try {
      const id = req.params.id as string;
      const roadmap = await RoadmapService.generateApprovalRoadmap(id);

      res.status(201).json({
        success: true,
        message: 'Statutory approval roadmap successfully generated by Gemini 2.5 Flash Approval Intelligence Engine',
        data: roadmap,
      });
    } catch (error: any) {
      const status = error.message.includes('not found') ? 404 : 400;
      res.status(status).json({
        success: false,
        message: error.message || 'Failed to generate approval roadmap',
      });
    }
  }

  /**
   * @route GET /api/v1/projects/:id/roadmap
   * @desc Retrieve existing roadmap for project
   */
  static async getRoadmap(req: Request, res: Response): Promise<void> {
    try {
      const id = req.params.id as string;
      const roadmap = await RoadmapService.getRoadmap(id);

      if (!roadmap) {
        res.status(200).json({
          success: true,
          data: {
            generated: false,
            approvals: [],
            totalApprovals: 0,
            totalDepartments: 0,
            estimatedTimeline: 0,
            requiredDocuments: [],
            parallelWorkflows: [],
            readinessScore: 0,
            message: 'No approval roadmap has been generated yet for this project.',
          },
        });
        return;
      }

      res.status(200).json({
        success: true,
        data: {
          generated: true,
          ...roadmap,
        },
      });
    } catch (error: any) {
      const status = error.message.includes('not found') ? 404 : 400;
      res.status(status).json({
        success: false,
        message: error.message || 'Failed to fetch approval roadmap',
      });
    }
  }

  /**
   * @route PUT /api/v1/approvals/:id/status
   * @desc Update approval status
   */
  static async updateApprovalStatus(req: Request, res: Response): Promise<void> {
    try {
      const id = req.params.id as string;
      const { status } = req.body;


      if (!status) {
        res.status(400).json({
          success: false,
          message: 'Status field is required',
        });
        return;
      }

      const validStatuses: ProjectApprovalStatus[] = [
        'Recommended',
        'Pending',
        'Documents Missing',
        'Ready to Apply',
        'Applied',
        'Under Review',
        'Inspection Pending',
        'Approved',
        'Rejected',
      ];

      if (!validStatuses.includes(status)) {
        res.status(400).json({
          success: false,
          message: `Invalid status. Must be one of: ${validStatuses.join(', ')}`,
        });
        return;
      }

      const updated = await RoadmapService.updateApprovalStatus(id, status);

      res.status(200).json({
        success: true,
        message: 'Approval status updated successfully',
        data: updated,
      });
    } catch (error: any) {
      const statusCode = error.message.includes('not found') ? 404 : 400;
      res.status(statusCode).json({
        success: false,
        message: error.message || 'Failed to update approval status',
      });
    }
  }
}

export default RoadmapController;
