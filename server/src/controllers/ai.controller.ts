import { Request, Response } from 'express';
import { AIRoadmapService } from '../services/ai/aiRoadmap.service';
import { AIComplianceService } from '../services/ai/aiCompliance.service';
import { AISchemeService } from '../services/ai/aiScheme.service';
import { AIDocumentService } from '../services/ai/aiDocument.service';
import { ApiResponse } from '../utils/apiResponse';
import { Logger } from '../utils/logger';

export class AIController {
  /**
   * @route   POST /api/v1/ai/generate-roadmap
   * @desc    Generate or return cached AI approval roadmap using Gemini 2.5 Flash and MongoDB
   * @body    { "projectId": "..." }
   */
  static async generateRoadmap(req: Request, res: Response): Promise<void> {
    try {
      const { projectId, regenerate } = req.body;
      if (!projectId) {
        res.status(400).json({
          success: false,
          message: 'projectId is required in request body',
        });
        return;
      }

      Logger.info(`API Request: generate-roadmap for projectId: ${projectId}, regenerate: ${regenerate}`);
      const roadmap = await AIRoadmapService.generateRoadmap(projectId, Boolean(regenerate));

      ApiResponse.success(
        res,
        {
          generated: true,
          ...roadmap,
        },
        roadmap.fromCache
          ? 'Cached approval roadmap retrieved successfully'
          : 'Approval roadmap successfully generated by Gemini 2.5 Flash Approval Intelligence Engine'
      );
    } catch (error: any) {
      Logger.error(`Error in generateRoadmap: ${error.message}`);
      res.status(500).json({
        success: false,
        message: error.message || 'Failed to generate AI approval roadmap',
      });
    }
  }

  /**
   * @route   POST /api/v1/ai/regenerate-roadmap/:projectId
   * @desc    Force deletion of previous roadmap, re-evaluate regulations with Gemini 2.5 Flash, and persist latest
   */
  static async regenerateRoadmap(req: Request, res: Response): Promise<void> {
    try {
      const projectId = req.params.projectId as string;
      if (!projectId) {
        res.status(400).json({
          success: false,
          message: 'projectId parameter is required',
        });
        return;
      }

      Logger.info(`API Request: regenerate-roadmap for projectId: ${projectId}`);
      const roadmap = await AIRoadmapService.generateRoadmap(projectId, true);

      ApiResponse.success(
        res,
        {
          generated: true,
          ...roadmap,
        },
        'Statutory approval roadmap successfully regenerated by Gemini 2.5 Flash'
      );
    } catch (error: any) {
      Logger.error(`Error in regenerateRoadmap: ${error.message}`);
      res.status(500).json({
        success: false,
        message: error.message || 'Failed to regenerate approval roadmap',
      });
    }
  }

  /**
   * @route   GET /api/v1/ai/roadmap/:projectId
   * @desc    Retrieve existing stored roadmap for a project
   */
  static async getRoadmap(req: Request, res: Response): Promise<void> {
    try {
      const projectId = req.params.projectId as string;
      const roadmap = await AIRoadmapService.getRoadmap(projectId);

      if (!roadmap) {
        res.status(404).json({
          success: false,
          message: 'No approval roadmap found for this project.',
        });
        return;
      }

      ApiResponse.success(
        res,
        {
          generated: true,
          ...roadmap,
        },
        'Approval roadmap retrieved'
      );
    } catch (error: any) {
      Logger.error(`Error in getRoadmap: ${error.message}`);
      res.status(500).json({
        success: false,
        message: error.message || 'Failed to retrieve approval roadmap',
      });
    }
  }

  /**
   * @route   POST /api/v1/ai/compliance-score
   * @desc    Calculate AI compliance score, risk level, strengths, weaknesses, and explanation
   * @body    { "projectId": "..." }
   */
  static async calculateComplianceScore(req: Request, res: Response): Promise<void> {
    try {
      const projectId = req.body.projectId || (req.query.projectId as string) || (req.params.projectId as string);
      if (!projectId) {
        res.status(400).json({
          success: false,
          message: 'projectId is required in request body',
        });
        return;
      }

      Logger.info(`API Request: compliance-score calculation for projectId: ${projectId}`);
      const complianceResult = await AIComplianceService.calculateComplianceScore(projectId);

      res.status(200).json({
        success: true,
        score: complianceResult.score,
        risk: complianceResult.risk,
        strengths: complianceResult.strengths,
        weaknesses: complianceResult.weaknesses,
        recommendations: complianceResult.recommendations,
        missingApprovals: complianceResult.missingApprovals,
        missingDocuments: complianceResult.missingDocuments,
        inspectionReadiness: complianceResult.inspectionReadiness,
        expectedApprovalTime: complianceResult.expectedApprovalTime,
        explanation: complianceResult.explanation,
        data: complianceResult,
        message: 'AI compliance score calculated and stored successfully',
      });
    } catch (error: any) {
      Logger.error(`Error in calculateComplianceScore: ${error.message}`);
      res.status(500).json({
        success: false,
        message: error.message || 'Failed to calculate compliance score',
      });
    }
  }

  /**
   * @route   POST /api/v1/ai/recommend-schemes
   * @desc    Recommend government schemes dynamically based on Industry, Investment, MSME status, Women entrepreneur, Startup, District, Employment
   * @body    { industry, investment, isMsme, isWomenEntrepreneur, isStartup, district, employment, projectId }
   */
  static async recommendSchemes(req: Request, res: Response): Promise<void> {
    try {
      Logger.info(`API Request: recommend-schemes with payload: ${JSON.stringify(req.body)}`);
      const profile = await AISchemeService.resolveInputProfile(req.body);
      const schemes = await AISchemeService.recommendSchemes(profile);

      res.status(200).json({
        success: true,
        schemes,
        data: schemes,
        count: schemes.length,
        profile,
        message: 'Government schemes recommended successfully by Gemini 2.5 Flash',
      });
    } catch (error: any) {
      Logger.error(`Error in recommendSchemes: ${error.message}`);
      res.status(500).json({
        success: false,
        message: error.message || 'Failed to recommend government schemes',
      });
    }
  }

  /**
   * @route   POST /api/v1/ai/analyze-document
   * @desc    Analyze uploaded statutory document using Gemini Vision, extract key fields, compute reusability, and store metadata in MongoDB
   * @body    Multipart file or JSON { fileBase64, mimeType, fileName, projectId, documentId, documentName }
   */
  static async analyzeDocument(req: Request, res: Response): Promise<void> {
    try {
      const file = req.file;
      const body = req.body || {};

      const fileName = file?.originalname || body.fileName || body.name || 'uploaded_document';
      const mimeType = file?.mimetype || body.mimeType || 'application/pdf';
      const fileSize = file?.size || body.fileSize || 0;
      const filePath = file?.path;
      const fileBuffer = file?.buffer;
      const fileBase64 = body.fileBase64;
      const projectId = body.projectId;
      const documentId = body.documentId;
      const documentName = body.documentName || body.name;

      Logger.info(`API Request: analyze-document for file: "${fileName}", projectId: ${projectId}, documentId: ${documentId}`);

      const analysis = await AIDocumentService.analyzeDocument({
        fileBuffer,
        filePath,
        fileBase64,
        mimeType,
        fileName,
        originalName: fileName,
        fileSize,
        projectId,
        documentId,
        documentName,
      });

      res.status(200).json({
        success: true,
        documentType: analysis.documentType,
        expiry: analysis.expiry,
        reusableFor: analysis.reusableFor,
        extractedFields: analysis.extractedFields,
        confidence: analysis.confidence,
        department: analysis.department,
        reusableCount: analysis.reusableCount,
        message: analysis.message, // "Reusable for 4 Approvals"
        data: analysis,
      });
    } catch (error: any) {
      Logger.error(`Error in analyzeDocument: ${error.message}`);
      res.status(500).json({
        success: false,
        message: error.message || 'Failed to analyze document with Gemini Vision',
      });
    }
  }
}

export default AIController;
